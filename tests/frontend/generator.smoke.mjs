import {chromium} from '@playwright/test';
import {XMLParser} from 'fast-xml-parser';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.BASE_URL||'http://127.0.0.1:3112';
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH}:{}),args:['--no-sandbox','--enable-unsafe-swiftshader']});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>{errors.push(error.message);console.error('PAGEERROR',error.message)});
 page.on('crash',()=>console.error('PAGECRASH'));
 page.on('console',msg=>{if(msg.type()==='error')console.error('CONSOLE',msg.text())});
 await page.goto(base+'/create',{waitUntil:'networkidle'});
 await page.locator('.map-loading').waitFor({state:'hidden',timeout:45000});
 await page.getByLabel('Where shall we start?').fill('Collingham');
 await page.getByRole('button',{name:'Search places'}).click();
 await page.getByRole('button',{name:'Collingham (village)'}).click();
 const responsePromise=page.waitForResponse(response=>response.url().endsWith('/api/generate'));
 await page.getByRole('button',{name:'Generate walks'}).click();
 const response=await responsePromise;assert.equal(response.status(),200);
 const data=await response.json();
 assert.equal(data.routes.length,5,'Collingham should offer five distinct mapped routes');
 assert.equal(await page.locator('.auto-results article').count(),5);
 const lengths=data.routes.map(route=>route.distanceMeters);
 assert.ok(lengths.every((length,index)=>index===0||length>lengths[index-1]));
 assert.ok(data.routes.every(route=>route.facilityStatus==='available'));
 assert.ok(data.routes.some(route=>route.facilities.counts.pub+route.facilities.counts.cafe>0));
 assert.ok(data.routes.some(route=>route.facilities.nearbyPlaces?.some(place=>place.name.startsWith('Beyond Coffee'))&&route.facilities.nearbyPlaces?.some(place=>place.name.startsWith('The Allotment'))),'Collingham generation should include both separate local cafe listings');
 const fifth=data.routes[4];
 await page.locator('.auto-results article').last().getByRole('button',{name:'Show on map'}).click();
 await page.getByLabel('Walk title').waitFor();
 assert.equal(await page.getByLabel('Walk title').inputValue(),fifth.title);
 await page.getByText('Mapped places near this walk',{exact:true}).first().waitFor();
 await page.locator('.nearby-facilities .facility-counts').waitFor();
 await page.getByText('Food & drink worth a detour').waitFor();
 await page.getByText('Beyond Coffee Collingham',{exact:true}).first().waitFor();
 await page.getByText('The Allotment Kitchen And Deli',{exact:true}).first().waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/tmp/fmw-generator-mobile.png',fullPage:true});
 const gpxDownload=page.waitForEvent('download');
 await page.locator('.auto-results article').last().getByRole('button',{name:'GPX'}).click();
 const gpx=await gpxDownload;
 const gpxPath='/tmp/fmw-generated.gpx';await gpx.saveAs(gpxPath);
 const parsed=new XMLParser({ignoreAttributes:false}).parse(await fs.readFile(gpxPath,'utf8'));
 const track=parsed.gpx.trk.trkseg.trkpt;
 assert.equal(track.length,fifth.geometry.coordinates.length);
 assert.ok(Math.abs(Number(track[0]['@_lat'])-fifth.geometry.coordinates[0][1])<1e-6);
 const [pdf]=await Promise.all([
  page.waitForEvent('download'),
  page.locator('.auto-results article').last().getByRole('button',{name:'PDF',exact:true}).click(),
 ]);
 const pdfPath='/tmp/fmw-generated.pdf';await pdf.saveAs(pdfPath);
 assert.ok((await fs.readFile(pdfPath)).subarray(0,8).toString().startsWith('%PDF-1.'));
 const save=page.waitForResponse(r=>r.url().endsWith('/api/routes')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Save walk',exact:true}).click();
 const savedResponse=await save;assert.equal(savedResponse.status(),201);
 const id=(await savedResponse.json()).route.id;assert.ok(id);
 const stored=(await (await page.request.get(base+'/api/routes/'+id)).json()).route;
 assert.equal(stored.distanceMeters,fifth.distanceMeters);
 assert.equal(stored.geometry.coordinates.length,fifth.geometry.coordinates.length);
 const reroute=page.waitForResponse(r=>r.url().endsWith('/api/route')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Reverse'}).click();
 assert.equal((await reroute).status(),200,'reversed generated route should reroute');
 await page.getByRole('button',{name:'Save walk',exact:true}).click();
 const updated=await (await page.request.get(base+'/api/routes/'+id)).json();
 const closed=updated.route.geometry.coordinates;
 assert.ok(closed.length>3);
 assert.ok(Math.hypot(closed[0][0]-closed.at(-1)[0],closed[0][1]-closed.at(-1)[1])<0.0001,'edited route stays circular');
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Loop on'}).waitFor();
 page.once('dialog',dialog=>dialog.accept());
 const deleted=page.waitForResponse(r=>r.url().includes('/api/routes/'+id+'?revision=')&&r.request().method()==='DELETE');
 await page.getByRole('button',{name:'Delete walk'}).click();assert.equal((await deleted).status(),204);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({status:'PASS',generated:5,lengthKm:lengths.map(n=>+(n/1000).toFixed(2)),facilityCounts:data.routes.map(route=>route.facilities.counts),gpxPoints:track.length,pdfBytes:(await fs.stat(pdfPath)).size,mobileOverflow:false,pageErrors:errors}));
 await context.close();
}finally{await browser.close()}
